const DICT: Record<Lang, Record<TKey, string>> = { id, en };

type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, vars?: Vars): string {
	let s = DICT[lang][key] ?? DICT.id[key] ?? key;
	if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
	return s;
}

/** Bentuk tunggal/jamak: kunci dasar + `.one` / `.other` */
export function translateN(lang: Lang, base: string, n: number, vars?: Vars): string {
	const key = `${base}.${n === 1 ? 'one' : 'other'}` as TKey;
	return translate(lang, key, { n, ...vars });
}

/** Alasan pembatalan otomatis disimpan dalam Bahasa Indonesia; terjemahkan bila dikenal */
export function systemText(lang: Lang, text: string | null | undefined): string {
	if (!text) return '';
	const key = `sys.${text}` as TKey;
	return key in DICT.id ? translate(lang, key) : text;
}

/** Sisa waktu PO, mis. "Sisa 5 hari" / "5 days left" */
export function timeLeftLabel(lang: Lang, closesAt: number, now: number): string {
	const ms = closesAt - now;
	if (ms <= 0) return translate(lang, 'time.closed');
	const days = Math.floor(ms / 86_400_000);
	const hours = Math.floor(ms / 3_600_000);
	if (days >= 1) return translateN(lang, 'time.days', days);
	if (hours >= 1) return translateN(lang, 'time.hours', hours);
	return translate(lang, 'time.underHour');
}

/** Teks alasan item keranjang tidak bisa dipesan */
export function cartProblemText(lang: Lang, problem: string, closesAt?: number | null): string {
	const key = `cart.problem.${problem}` as TKey;
	if (!(key in DICT.id)) return problem;
	return translate(lang, key, closesAt ? { date: fmtDayShort(closesAt, lang) } : undefined);
}
